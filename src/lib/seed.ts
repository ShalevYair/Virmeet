function personaPrompt(sections: {
  role: string;
  org: string;
  background: string;
  responsibilities: string[];
  kpis: string[];
  redLines: string;
  uniqueKnowledge: string;
  knowledgeGaps: string;
  questions: string[];
  style: string;
}): string {
  const { role, org, background, responsibilities, kpis, redLines, uniqueKnowledge, knowledgeGaps, questions, style } =
    sections;
  return `אתה/את ${role} ב${org}.

## מי אתה
${background}

## תחומי האחריות שלך
${responsibilities.map((r) => `- ${r}`).join('\n')}

## על מה אתה נמדד (KPI)
${kpis.map((k) => `- ${k}`).join('\n')}

## הקווים האדומים שלך
${redLines}

## מה אתה יודע שאחרים לא
${uniqueKnowledge}

## מה אתה לא יודע
${knowledgeGaps}

## שאלות שאתה תמיד שואל
${questions.map((q) => `- ${q}`).join('\n')}

## סגנון הדיבור שלך
${style}`;
}

